"""Writes src/town_map.hpp from ref/charnfen.txt, so Charnfen is built into the game (desktop and phone alike)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
rows = open(os.path.join(here, '..', 'ref', 'charnfen.txt'), encoding='utf-8').read().rstrip('\n').split('\n')
o = ['// Generated by tools/gen_town.py from ref/charnfen.txt.', '#pragma once', '', 'namespace town {',
     '// Charnfen, row by row, as drawn by hand', 'inline const char* const MAP[] = {']
def lit(r): return ''.join(c if c.isascii() and c not in '\\"' else '\\' + c if c.isascii() else '\\u%04x' % ord(c) for c in r)
o += ['    "' + lit(r) + '",' for r in rows]
o += ['};', 'inline constexpr int ROWS = %d;' % len(rows), '}  // namespace town', '']
open(os.path.join(here, '..', 'src', 'town_map.hpp'), 'w', encoding='utf-8').write('\n'.join(o))
