"""Writes src/lore.hpp from ref/lore.py."""
import importlib.util, os
here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('l', os.path.join(here, '..', 'ref', 'lore.py'))
L = importlib.util.module_from_spec(spec); spec.loader.exec_module(L)
def s(x): return '"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"'
def lst(xs): return '{' + ', '.join(s(x) for x in xs) + '}'
o = ['// Generated by tools/gen_lore.py from ref/lore.py.', '#pragma once', '#include <map>', '#include <string>', '#include <vector>', '', 'namespace lore {']
o.append('inline const std::vector<std::string> INTRO = ' + lst(L.INTRO) + ';')
o.append('inline const std::vector<std::vector<std::string>> ACT_OPEN = {' + ', '.join(lst(a) for a in L.ACT_OPEN) + '};')
o.append('inline const std::vector<std::vector<std::string>> WRITINGS = {\n' + ',\n'.join('    ' + lst(w) for w in L.WRITINGS) + '};')
o.append('inline const std::map<std::string, std::string> BOSS_WAKE = {' + ', '.join('{%s, %s}' % (s(k), s(v)) for k, v in L.BOSS_WAKE.items()) + '};')
o.append('inline const std::map<std::string, std::string> BOSS_DIES = {' + ', '.join('{%s, %s}' % (s(k), s(v)) for k, v in L.BOSS_DIES.items()) + '};')
o.append('inline const std::string WAYSTATION = ' + s(L.WAYSTATION) + ';')
o.append('inline const std::vector<std::string> VICTORY = ' + lst(L.VICTORY) + ';')
o.append('}  // namespace lore')
open(os.path.join(here, '..', 'src', 'lore.hpp'), 'w').write('\n'.join(o) + '\n')
