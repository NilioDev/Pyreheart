"""Writes src/data.hpp from ref/data.py (the design tables, kept in Python because they read easily)."""
import importlib.util, os
here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('d', os.path.join(here, '..', 'ref', 'data.py'))
D = importlib.util.module_from_spec(spec); spec.loader.exec_module(D)

def s(x): return '"' + str(x).replace('\\', '\\\\').replace('"', '\\"') + '"'
def cp(ch): return '0x%X' % ord(ch)
def col(t): return '0x%02X%02X%02X' % tuple(t) if t else '-1'
def lst(xs): return '{' + ', '.join(s(x) for x in xs) + '}'
def b(v): return 'true' if v else 'false'

o = ['// Generated by tools/gen_data.py from ref/data.py: change the tables there and run it again.',
     '#pragma once', '#include "defs.hpp"', '', 'namespace data {']
names = ['WALL', 'FLOOR', 'DOOR', 'OPEN', 'STAIRS', 'WATER', 'SHALLOW', 'RUBBLE', 'FOUNTAIN', 'LAVA', 'UPSTAIRS', 'CHEST', 'OPENCHEST', 'SHRINE', 'USED',
         'SNOW', 'PATH', 'GRAVE', 'CROSS', 'TREE', 'PEW', 'ALTAR', 'EMBER', 'WELL', 'BOARD', 'WINDOW', 'LIT', 'ICE', 'CRACK', 'PILLAR', 'FLAGS', 'FIRE', 'STONES', 'CHIMNEY', 'HEALER', 'SMITH', 'DIGGER', 'TORCH', 'CANDLE', 'OPENGRAVE', 'GUARD', 'BARRICADE']
o.append('enum Tile { ' + ', '.join(names) + ', TILE_COUNT };')
o.append('inline const TileDef TILES[] = {')
for t in D.TILES: o.append('    {%s, %s, %s, %s, %s},' % (cp(t[0]), col(t[1]), b(t[2]), b(t[3]), s(t[4])))
o.append('};')
o.append('inline bool blocks(int t) { switch (t) { ' + ' '.join('case %s:' % names[i] for i in sorted(D.BLOCKS_MOVE)) + ' return true; default: return false; } }')
o.append('constexpr int FLOORS = %d;' % D.FLOORS)
o.append('inline bool rest_after(int d) { return ' + ' || '.join('d == %d' % r for r in D.REST_AFTER) + '; }')
o.append('inline const ActDef ACTS[] = {')
for a in D.ACTS: o.append('    {%s, %s, %s, %s, %s},' % (s(a['name']), col(a['wall']), col(a['floor']), s(a['mood']), s(a['boss'])))
o.append('};')
o.append('inline const std::vector<MonDef> MONSTERS = {')
for k, m in D.M.items():
    shot = m.get('shot', ('*', (255, 255, 255)))
    o.append('    {%s, %s, %s, %s, %d, %d, %d, %d, %d, %d, %d, %s, %d, %s, %s, %s, %s, %d, %s, %s, %s, %s},' % (
        s(k), s(m['name']), cp(m['ch']), col(m['col']), m['hp'], m['dmg'][0], m['dmg'][1], m['acc'], m['ar'], m['spd'], m['xp'],
        s(m['ai']), m.get('rng', 1), cp(shot[0]), col(shot[1]), b(m.get('boss')), b(m.get('gear')),
        m.get('poison', 0), b(m.get('fire')), b(m.get('cold')), lst(m.get('moves', ())), b(m.get('undead'))))
o.append('};')
o.append('inline const std::vector<std::vector<std::pair<std::string, int>>> SPAWNS = {')
for act in D.SPAWNS: o.append('    {' + ', '.join('{%s, %d}' % (s(k), w) for k, w in act) + '},')
o.append('};')
o.append('inline const std::vector<std::pair<std::string, std::string>> AFFIXES = {' + ', '.join('{%s, %s}' % (s(k), s(v)) for k, v in D.AFFIXES.items()) + '};')
o.append('inline const std::vector<std::string> UNIQUE_FIRST = ' + lst(D.UNIQUE_FIRST) + ';')
o.append('inline const std::vector<std::string> UNIQUE_EPITHET = ' + lst(D.UNIQUE_EPITHET) + ';')
o.append('inline const std::vector<ClassDef> CLASSES = {')
for k in D.CLASS_ORDER:
    cl = D.CLASSES[k]
    o.append('    {%s, %s, %s, %d, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s},' % (s(k), s(cl['name']), col(cl['col']), cl['hp'], cl['mana'],
             cl['hp_lvl'], cl['mana_lvl'], cl['acc'], lst(cl['start']), lst(cl['skills']), lst(cl['kinds']), s(cl['about']),
             s(cl['res']), lst(cl['paths'])))
o.append('};')
o.append('inline const int SKILL_LEVELS[] = {' + ', '.join(str(x) for x in D.SKILL_LEVELS) + '};')
o.append('constexpr int PATH_LEVEL = %d;' % D.PATH_LEVEL)
o.append('inline const std::vector<SkillDef> SKILLS = {')
for k, sk in D.SKILLS.items(): o.append('    {%s, %s, %d, %s, %s},' % (s(k), s(sk['name']), sk['mana'], b(sk['target']), s(sk['about'])))
o.append('};')
o.append('inline const std::vector<PerkDef> PERKS = {')
for k, (n, t, mx, cl, pa) in D.PERKS.items(): o.append('    {%s, %s, %s, %d, %s, %s},' % (s(k), s(n), s(t), mx, s(cl) if cl else '""', s(pa) if pa else '""'))
o.append('};')
o.append('inline const std::vector<std::string> SLOTS = ' + lst(D.SLOTS) + ';')
o.append('inline const std::vector<BaseDef> BASES = {')
for k, (n, slot, kind, tier, v) in D.BASES.items():
    lo, hi = (v if isinstance(v, tuple) else (0, 0)); ar = 0 if isinstance(v, tuple) else v
    o.append('    {%s, %s, %s, %s, %d, %d, %d, %d, %d},' % (s(k), s(n), s(slot), s(kind), tier, lo, hi, ar, D.STAFF_SPELL.get(k, 0)))
o.append('};')
for nm, tab in (('PREFIXES', D.PREFIXES), ('SUFFIXES', D.SUFFIXES)):
    o.append('inline const std::vector<AffixDef> %s = {' % nm)
    for k, (stat, (lo, hi), g, slots) in tab.items():
        o.append('    {%s, %s, %d, %d, %s, %s},' % (s(k), s(stat), lo, hi, g, lst(slots) if slots else '{}'))
    o.append('};')
o.append('inline const std::vector<std::pair<std::string, std::string>> STAT_TEXT = {' + ', '.join('{%s, %s}' % (s(k), s(v)) for k, v in D.STAT_TEXT.items()) + '};')
o.append('inline const std::vector<std::string> RARE_A = ' + lst(D.RARE_A) + ';')
o.append('inline const std::vector<std::pair<std::string, std::vector<std::string>>> RARE_B = {' + ', '.join('{%s, %s}' % (s(k), lst(v)) for k, v in D.RARE_B.items()) + '};')
o.append('inline const std::vector<UniqueDef> UNIQUES = {')
for n, bb, st in D.UNIQUES: o.append('    {%s, %s, {%s}},' % (s(n), s(bb), ', '.join('{%s, %d}' % (s(k), v) for k, v in st.items())))
o.append('};')
o.append('inline int rarity_col(const std::string& r) { ' + ' '.join('if (r == %s) return %s;' % (s(k), col(v)) for k, v in D.RARITY_COL.items()) + ' return 0xFFFFFF; }')
o.append('constexpr int BELT_MAX = %d;' % D.BELT_MAX)
o.append('constexpr int PACK_MAX = %d;' % D.PACK_MAX)
o.append('}  // namespace data')
open(os.path.join(here, '..', 'src', 'data.hpp'), 'w').write('\n'.join(o) + '\n')
