"""Writes src/data.hpp from ref/data.py (the design tables, kept in Python because they read easily)."""
import importlib.util, os
here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('d', os.path.join(here, '..', 'ref', 'data.py'))
D = importlib.util.module_from_spec(spec); spec.loader.exec_module(D)

