         'SNOW', 'PATH', 'GRAVE', 'CROSS', 'TREE', 'EMBER', 'WELL', 'BOARD', 'WINDOW', 'LIT', 'ICE', 'CRACK', 'FLAGS', 'FIRE', 'STONES',
         'CHIMNEY', 'HEALER', 'SMITH', 'DIGGER', 'OPENGRAVE', 'GUARD', 'BARRICADE',
