o.append('inline const PathDef PATHS[3][2] = {' + ', '.join('{' + ', '.join('{%s, %s, %s}' % (s(a), s(n), s(t)) for a, n, t in D.PATHS[k]) + '}' for k in D.STYLE_ORDER) + '};')
